// Compiles projects/centauri-bloom/bloom-kernels.wat into an inlined base64
// module (bloom-kernels.wasm.js) so the worker needs no extra fetch.
// Usage: npx -y -p wabt@1.0.39 node tools/build-bloom-wasm.mjs  (or with wabt installed)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(process.env.WABT_FROM ? path.join(process.env.WABT_FROM, 'x.js') : import.meta.url);
const wabt = await require('wabt')();
const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'projects', 'centauri-bloom');
const src = fs.readFileSync(path.join(dir, 'bloom-kernels.wat'), 'utf8');
const mod = wabt.parseWat('bloom-kernels.wat', src, { simd: true });
mod.validate();
const { buffer } = mod.toBinary({});
const b64 = Buffer.from(buffer).toString('base64');
fs.writeFileSync(path.join(dir, 'bloom-kernels.wasm.js'),
  '// Generated by tools/build-bloom-wasm.mjs from bloom-kernels.wat. Do not edit.\n' +
  `export const KERNELS_WASM_BASE64 = '${b64}';\n`);
console.log('wrote bloom-kernels.wasm.js,', buffer.length, 'bytes');
